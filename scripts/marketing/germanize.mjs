/**
 * Rewrites every mapped value in one table.
 *
 * Reads the column once and updates only the rows that actually change, rather
 * than firing an update per mapping per column, which was both four hundred
 * round trips and a malformed request: chaining a head select onto an update
 * fails rather than counting it.
 */
async function translateTable(table, columns) {
  const { data, error } = await db.from(table).select(["id", ...columns].join(", "));
  if (error) {
    if (/does not exist|column|relation/i.test(error.message)) return 0;
    throw new Error(`${table}: ${error.message}`);
  }

  let changed = 0;
  for (const row of data ?? []) {
    const patch = {};
    for (const column of columns) {
      const value = row[column];
      if (typeof value === "string" && TEXT[value] !== undefined && TEXT[value] !== value) {
        patch[column] = TEXT[value];
      }
    }
    if (Object.keys(patch).length === 0) continue;
    const { error: updateError } = await db.from(table).update(patch).eq("id", row.id);
    if (updateError) throw new Error(`${table}.${row.id}: ${updateError.message}`);
    changed += Object.keys(patch).length;
  }
  return changed;
}

