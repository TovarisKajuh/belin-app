  for (const [table, columns] of CONTENT) {
    const changed = await translateTable(table, columns);
    if (changed) console.log(`  ${table.padEnd(22)} ${changed} value(s)`);
    total += changed;
  }

  console.log(`\ndemo dressed in German: ${total} content value(s) rewritten.`);
  console.log("Run `npm run seed` afterwards to restore the Slovenian demo.");
